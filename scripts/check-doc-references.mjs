/**
 *   node scripts/check-doc-references.mjs   # fail if a tracked .md names something absent
 *
 * Two kinds of reference are resolved: a `pnpm <script>` against package.json, and a path —
 * either backticked or a relative markdown link target — against the filesystem.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { dirname, posix, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const git = (args) =>
  execFileSync("git", args, { encoding: "utf8", cwd: root })
    .split("\n")
    .filter(Boolean);

// Third-party capture and generated output. Excluded as scan sources AND as resolution targets:
// docs/ui-reference/ paths appear in the agent definitions as files an agent is told to write, so
// requiring them to exist would fail on work that has not run yet.
const EXCLUDED = [/^docs\/ui-reference\//, /^technomancy_artifacts\//];

// Generated by scripts/generate-diagrams.mjs. Its body is fenced Mermaid, whose node text parses
// as prose.
const GENERATED = ["docs/diagrams/SOURCES.md"];

const scripts = new Set(
  Object.keys(
    JSON.parse(readFileSync(resolve(root, "package.json"), "utf8")).scripts,
  ),
);

// pnpm's own subcommands, which `pnpm <name>` resolves before ever consulting package.json.
const PNPM_BUILTINS = new Set(
  `add audit bin config create dedupe deploy dlx doctor env exec fetch import init install licenses
   link list ls outdated pack patch prune publish rebuild remove root run server setup store unlink
   update why`.split(/\s+/),
);

// A path whose first segment is not tracked is either build output or a third-party name. Both
// must be skipped rather than resolved: `coverage/` exists only after a test run, so requiring it
// would pass on this machine and fail on a clean checkout.
const trackedRoots = new Set(
  git(["ls-files"]).map((path) => path.split("/")[0]),
);

// `ls-files` reports the index, which still lists a file deleted from the worktree — the
// existsSync is what keeps a commit that deletes a .md from crashing this.
const files = git(["ls-files", "*.md"]).filter(
  (path) =>
    !EXCLUDED.some((rule) => rule.test(path)) &&
    !GENERATED.includes(path) &&
    existsSync(resolve(root, path)),
);

const findings = [];
const report = (file, line, reference, reason) =>
  findings.push({ file, line, reference, reason });

// Rejects anything that is not a repository path before resolving it. Each rule is here because a
// real token in this corpus needed it: `window.Lenis` and `ctx.measureText("0").width` (expression),
// `/api/leads` and `0.0.0.0/0` (leading slash), `@playwright/test` and `next/image` (package),
// `articles/<slug>.tsx` and `transitions/*/styles.json` (placeholder, glob).
function candidatePath(token) {
  if (/\s/.test(token) || !token.includes("/")) return null;
  if (/^[/@~]|^https?:/.test(token)) return null;
  if (/[*{}<>]/.test(token)) return null;
  // `src/app/(site)/page.tsx:HomePage` names a symbol inside a file; resolve the file.
  const path = token.replace(/:[A-Za-z_$][\w$]*$/, "").replace(/\/+$/, "");
  if (!trackedRoots.has(path.split("/")[0])) return null;
  if (EXCLUDED.some((rule) => rule.test(path))) return null;
  return path;
}

for (const file of files) {
  const lines = readFileSync(resolve(root, file), "utf8").split("\n");
  let fenced = false;

  lines.forEach((text, index) => {
    if (/^\s*```/.test(text)) fenced = !fenced;
    const number = index + 1;

    for (const [, run, name] of text.matchAll(
      /\bpnpm (run )?([a-z][\w:-]*)/g,
    )) {
      if (scripts.has(name)) continue;
      if (!run && PNPM_BUILTINS.has(name)) continue;
      report(file, number, `pnpm ${name}`, "no such script in package.json");
    }

    for (const [, token] of text.matchAll(/`([^`\n]+)`/g)) {
      const path = candidatePath(token);
      if (path && !existsSync(resolve(root, path))) {
        report(file, number, token, "path does not exist");
      }
    }

    // Link targets resolve against the document's own directory, which is how
    // docs/diagrams/README.md correctly links [`SOURCES.md`](SOURCES.md).
    if (fenced) return;
    for (const [, target] of text.matchAll(/\]\(([^)\s]+)\)/g)) {
      if (/^([a-z]+:|[/#])/.test(target)) continue;
      const path = posix.normalize(
        posix.join(dirname(file), target.split("#")[0]),
      );
      if (EXCLUDED.some((rule) => rule.test(path))) continue;
      if (!existsSync(resolve(root, path))) {
        report(file, number, target, "link target does not exist");
      }
    }
  });
}

if (findings.length > 0) {
  for (const { file, line, reference, reason } of findings) {
    console.error(`${file}:${line}  ${reference} — ${reason}`);
  }
  console.error(`\n${findings.length} stale reference(s) in documentation.`);
  process.exit(1);
}

console.log(`${files.length} markdown files checked, no stale references`);
